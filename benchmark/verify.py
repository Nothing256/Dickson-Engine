import subprocess
import os
import re
import sympy as sp
from sympy.abc import x

# --- Configuration ---
DICKSON_BIN = "build/bin/dickson_bench"

def parse_traces(output):
    traces = {}
    for line in output.splitlines():
        match = re.search(r"Trace T\[(\d+)\] = (\d+)", line)
        if match:
            k = int(match.group(1))
            val = int(match.group(2))
            traces[k] = val
    return traces

def run_verification():
    print("\n=========================================================")
    print("=== Algebraic Verification: Dickson Engine V2 ===")
    print("=========================================================")
    print("This script uses Sympy to rigorously verify that the traces")
    print("generated by the Dickson Engine construct a valid primitive")
    print("polynomial that divides X^n - 1 over GF(p).")
    
    if not os.path.exists(DICKSON_BIN):
        print("Error: Binaries not found. Please compile them first via 'make' in build/.")
        return

    # A few random tests for p and n = p^2+p+1
    test_cases = [
        (2, 7),
        (3, 13),
        (5, 31),
        (7, 57),
        (11, 133)
    ]
    
    pass_count = 0
    fail_count = 0

    for p, n in test_cases:
        print(f"\n[Testing] p={p}, n={n} (m=3)")
        cmd = [DICKSON_BIN, str(p), "1", str(n), "--random"]
        
        try:
            result = subprocess.run(cmd, capture_output=True, text=True, check=True)
            traces = parse_traces(result.stdout)
            
            if 1 not in traces or 2 not in traces or 3 not in traces:
                print("  ❌ FAIL: Could not parse traces T[1], T[2], T[3] from engine output.")
                fail_count += 1
                continue
            
            T1, T2, T3 = traces[1], traces[2], traces[3]
            print(f"  > Engine Extracted Traces: T1={T1}, T2={T2}, T3={T3}")
            
            # Construct G(X) = X^3 - T1*X^2 + T2*X - T3 over GF(p)
            G_expr = x**3 - T1*x**2 + T2*x - T3
            G = sp.Poly(G_expr, x, domain=sp.GF(p))
            
            # Target polynomial f(X) = X^n - 1 over GF(p)
            f_expr = x**n - 1
            f = sp.Poly(f_expr, x, domain=sp.GF(p))
            
            # Mathematical Verification: does G(X) divide f(X)?
            q, r = f.div(G)
            
            if r.is_zero:
                print(f"  ✅ PASS: G(X) exactly divides X^{n} - 1 over GF({p})!")
                pass_count += 1
            else:
                print(f"  ❌ FAIL: G(X) does NOT divide X^{n} - 1 over GF({p}). Remainder: {r}")
                fail_count += 1
                
        except subprocess.CalledProcessError as e:
            print(f"  ❌ FAIL: Engine crashed for p={p}, n={n}")
            fail_count += 1

    print("\n=========================================================")
    print(f"Verification Summary: {pass_count} Passed, {fail_count} Failed.")

if __name__ == "__main__":
    run_verification()
